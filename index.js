// ─── PARSE & EKSEKUSI TOOL DARI RESPONSE AI ──────────────────────────────────
async function parseAndExecuteTools(aiText) {
  let finalText = aiText;
  const toolOutputs = [];

  // 1. Shell execution
  const shellRegex = /```shell\n([\s\S]*?)```/g;
  let match;
  while ((match = shellRegex.exec(aiText)) !== null) {
    const command = match[1].trim();
    console.log(`[SHELL] Executing: ${command}`);
    const output = await runShell(command);
    toolOutputs.push(`\n⚡ *Shell:* \`${command}\`\n\`\`\`\n${output.substring(0, 2000)}\n\`\`\``);
    finalText = finalText.replace(match[0], '');
  }

  // 2. Create wallet
  const walletRegex = /```create_wallet\n([\s\S]*?)```/g;
  while ((match = walletRegex.exec(aiText)) !== null) {
    const label = match[1].trim();
    console.log(`[WALLET] Creating wallet: ${label}`);
    try {
      const wallet = await createEthWallet(label);
      toolOutputs.push(`\n💰 *Wallet dibuat:*\n• Label: ${wallet.label}\n• Private Key: \`${wallet.privateKey}\`\n• ⚠️ Simpan private key ini baik-baik!`);
    } catch (e) {
      toolOutputs.push(`\n❌ Gagal buat wallet: ${e.message}`);
    }
    finalText = finalText.replace(match[0], '');
  }

  // 3. List wallets
  if (aiText.includes('```list_wallets```')) {
    const wallets = loadWallets();
    if (wallets.length === 0) {
      toolOutputs.push('\n📭 Belum ada wallet tersimpan.');
    } else {
      const list = wallets.map((w, i) =>
        `${i + 1}. *${w.label}* — \`${w.privateKey.substring(0, 8)}...\` (${w.createdAt})`
      ).join('\n');
      toolOutputs.push(`\n💼 *Daftar Wallet (${wallets.length}):*\n${list}`);
    }
    finalText = finalText.replace('```list_wallets```', '');
  }

  // 4. Clear memory
  if (aiText.includes('```clear_memory```')) {
    clearMemory();
    toolOutputs.push('\n🧹 Memory percakapan dihapus.');
    finalText = finalText.replace('```clear_memory```', '');
  }

  return {
    text: finalText.trim(),
    toolOutputs
  };
}

// ─── KIRIM KE LLM ─────────────────────────────────────────────────────────────
async function askLLM(userMessage, history) {
  const messages = [
    { role: 'system', content: SYSTEM_PROMPT },
    ...history,
    { role: 'user', content: userMessage }
  ];

  const response = await axios.post(`${BASE_URL}/chat/completions`, {
    model: DEFAULT_MODEL,
    messages,
    max_tokens: 1500,
    temperature: 0.7
  }, {
    headers: { Authorization: `Bearer ${API_KEY}` },
    timeout: 60000
  });

  return response.data.choices[0].message.content;
}

