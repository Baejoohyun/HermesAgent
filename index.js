const DEFAULT_MODEL = process.env.DEFAULT_MODEL || 'nvidia/meta/llama-3.3-70b-instruct';
const WALLET_FILE = path.join(__dirname, 'wallets.json');
const MEMORY_FILE = path.join(__dirname, 'memory.json');
const MAX_HISTORY = 20; // maksimal pesan yang diingat

console.log('[Hermes] Bot starting...');
console.log(`[Hermes] Owner: ${OWNER_ID}`);
console.log(`[Hermes] Model: ${DEFAULT_MODEL}`);

// ─── MEMORY / HISTORY ─────────────────────────────────────────────────────────
function loadMemory() {
  try {
    if (fs.existsSync(MEMORY_FILE)) {
      return JSON.parse(fs.readFileSync(MEMORY_FILE, 'utf8'));
    }
  } catch (e) {}
  return [];
}

function saveMemory(history) {
  try {
    // Simpan hanya MAX_HISTORY pesan terakhir
    const trimmed = history.slice(-MAX_HISTORY);
    fs.writeFileSync(MEMORY_FILE, JSON.stringify(trimmed, null, 2));
    return trimmed;
  } catch (e) {
    return history;
  }
}

function clearMemory() {
  try { fs.writeFileSync(MEMORY_FILE, '[]'); } catch (e) {}
}

// ─── WALLET HELPERS ───────────────────────────────────────────────────────────
function loadWallets() {
  try {
    if (fs.existsSync(WALLET_FILE)) {
      return JSON.parse(fs.readFileSync(WALLET_FILE, 'utf8'));
    }
  } catch (e) {}
  return [];
}

function saveWallet(wallet) {
  const wallets = loadWallets();
  wallets.push({ ...wallet, createdAt: new Date().toISOString() });
  fs.writeFileSync(WALLET_FILE, JSON.stringify(wallets, null, 2));
}

// ─── TOOL: JALANKAN BASH ──────────────────────────────────────────────────────
async function runShell(command, timeoutMs = 30000) {
  try {
    const { stdout, stderr } = await execAsync(command, {
      timeout: timeoutMs,
      maxBuffer: 1024 * 1024 * 5 // 5MB
    });
    return stdout || stderr || '(no output)';
  } catch (err) {
    return `[ERROR] ${err.message}`;
  }
}

// ─── TOOL: BUAT WALLET ETHEREUM ───────────────────────────────────────────────
async function createEthWallet(label = '') {
  // Gunakan node crypto untuk generate key pair sederhana
  // (tanpa ethers.js — pakai openssl saja)
  const { stdout } = await execAsync(
    'node -e "const crypto=require(\'crypto\');' +
    'const {privateKey}=crypto.generateKeyPairSync(\'ec\',{namedCurve:\'secp256k1\'});' +
    'const pk=privateKey.export({type:\'sec1\',format:\'der\'}).toString(\'hex\');' +
    'console.log(JSON.stringify({privateKey:pk.substring(14,78)}));"'
  );
  const data = JSON.parse(stdout.trim());
  const wallet = {
    label: label || `wallet_${Date.now()}`,
    privateKey: data.privateKey,
    note: 'Generated by Hermes Agent'
  };
  saveWallet(wallet);
  return wallet;
}

